//! Resolve complete artist credits once, before tracks reach storage or consumers.
use serde_json::Value;

const SEPARATOR: &str = " · ";

fn join<'a>(names: impl IntoIterator<Item = &'a str>) -> String {
    let mut artists = Vec::new();
    for name in names {
        let name = name.trim();
        if !name.is_empty() && !artists.contains(&name) {
            artists.push(name);
        }
    }
    artists.join(SEPARATOR)
}

/// Only read the credits line of a publisher-generated description. The album
/// occupies a separate line and must never become an artist credit.
fn publisher_credits(metadata: &Value) -> Option<String> {
    let description = metadata["description"].as_str()?.trim();
    if !description.starts_with("Provided to YouTube by ")
        || !description.ends_with("Auto-generated by YouTube.")
    {
        return None;
    }
    let line = description
        .lines()
        .skip(1)
        .find(|line| !line.trim().is_empty())?;
    let (_, credits) = line.split_once(SEPARATOR)?;
    let credits = join(credits.split(SEPARATOR));
    (!credits.is_empty()).then_some(credits)
}

/// Shared by URL imports and Google playlist sync. Preserve names containing
/// commas or ampersands; those characters do not reliably separate artists.
pub fn resolve(metadata: &Value) -> String {
    let listed = join(
        metadata["artists"]
            .as_array()
            .into_iter()
            .flatten()
            .filter_map(Value::as_str),
    );
    if !listed.is_empty() {
        return listed;
    }
    if let Some(credits) = publisher_credits(metadata) {
        return credits;
    }
    for field in ["artist", "videoOwnerChannelTitle", "uploader", "channel"] {
        if let Some(value) = metadata[field].as_str() {
            let value = value.trim().trim_end_matches(" - Topic").trim();
            if !value.is_empty() {
                return value.to_owned();
            }
        }
    }
    String::new()
}

/// Desktop media metadata expects an array, rather than a combined credit.
pub fn names(credit: &str) -> Vec<String> {
    credit
        .split(SEPARATOR)
        .filter(|s| !s.is_empty())
        .map(str::to_owned)
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn reads_every_artist_and_preserves_punctuation() {
        let value = json!({"artists": [" Orchestra ", "Bach, J.S.", "Simon & Garfunkel", "Orchestra", "", null], "artist": "Orchestra", "album": "Album"});
        let credit = resolve(&value);
        assert_eq!(
            names(&credit),
            ["Orchestra", "Bach, J.S.", "Simon & Garfunkel"]
        );
    }

    #[test]
    fn sync_and_import_share_publisher_credits_without_album() {
        let description = "Provided to YouTube by Publisher\n\nCantata · Orchestra · Karl Richter · Choir · Johann Sebastian Bach\n\nBach: Cantatas for Easter\n\nAuto-generated by YouTube.";
        for value in [
            json!({"description": description, "videoOwnerChannelTitle": "Orchestra - Topic"}),
            json!({"description": description, "artist": "Orchestra"}),
        ] {
            assert_eq!(
                resolve(&value),
                "Orchestra · Karl Richter · Choir · Johann Sebastian Bach"
            );
        }
    }

    #[test]
    fn falls_back_without_guessing_from_unstructured_descriptions() {
        assert_eq!(
            resolve(
                &json!({"artists": [], "artist": "", "uploader": "Channel - Topic", "description": "Track · False artist"})
            ),
            "Channel"
        );
        assert_eq!(resolve(&json!({})), "");
        assert_eq!(
            resolve(&json!({"artist": "Earth, Wind & Fire"})),
            "Earth, Wind & Fire"
        );
    }
}
