//! Recover publisher-supplied music names without guessing missing title text.
use serde_json::Value;

pub fn complete<'a>(title: &'a str, candidate: Option<&'a str>) -> &'a str {
    let prefix = title
        .strip_suffix("...")
        .or_else(|| title.strip_suffix('…'));
    match (prefix, candidate.map(str::trim)) {
        (Some(prefix), Some(full))
            if full.starts_with(prefix)
                && full.len() > prefix.len()
                && !full.ends_with("...")
                && !full.ends_with('…') =>
        {
            full
        }
        _ => title,
    }
}

pub fn from_snippet(snippet: &Value) -> String {
    let title = snippet["title"].as_str().unwrap_or("Unavailable video");
    let description = snippet["description"].as_str().unwrap_or("");
    // Only the structured publisher block in auto-generated music descriptions
    // is authoritative; arbitrary user descriptions must not replace titles.
    let mut lines = description.lines();
    let publisher = lines
        .next()
        .unwrap_or("")
        .starts_with("Provided to YouTube by ");
    let music_line = lines.find(|line| !line.trim().is_empty());
    let candidate = if publisher
        && description
            .trim_end()
            .ends_with("Auto-generated by YouTube.")
    {
        music_line.and_then(|line| line.split_once(" · ").map(|(track, _)| track))
    } else {
        None
    };
    complete(title, candidate).to_owned()
}

/// Repair existing shortened cached titles using batched, read-only YouTube requests.
/// Only exact original title matches are updated, preserving concurrent edits.
pub fn repair_cache(apply: bool) -> anyhow::Result<()> {
    use crate::{db, integrations};
    use anyhow::Context;
    use std::{collections::BTreeSet, time::Duration};
    let mut db = db::library()?;
    let entries = db
        .conn
        .prepare(
            "SELECT DISTINCT url,title FROM entries WHERE title LIKE '%...' OR title LIKE '%…'",
        )?
        .query_map([], |r| Ok((r.get::<_, String>(0)?, r.get::<_, String>(1)?)))?
        .collect::<anyhow::Result<Vec<_>, _>>()?;
    let ids: BTreeSet<String> = entries
        .iter()
        .filter_map(|(url, _)| {
            url::Url::parse(url)
                .ok()?
                .query_pairs()
                .find(|(k, _)| k == "v")
                .map(|(_, v)| v.into_owned())
        })
        .collect();
    let ids: Vec<_> = ids.into_iter().collect();
    let token = integrations::google_access()?;
    let client = reqwest::blocking::Client::builder()
        .timeout(Duration::from_secs(30))
        .build()?;
    let mut fixes = Vec::new();
    for batch in ids.chunks(50) {
        let response: Value = client
            .get("https://www.googleapis.com/youtube/v3/videos")
            .bearer_auth(&token)
            .query(&[("part", "snippet"), ("id", &batch.join(","))])
            .send()?
            .error_for_status()?
            .json()?;
        for item in response["items"]
            .as_array()
            .context("Missing video metadata")?
        {
            let Some(id) = item["id"].as_str() else {
                continue;
            };
            let full = from_snippet(&item["snippet"]);
            let url = format!("https://www.youtube.com/watch?v={id}");
            for (_, old) in entries.iter().filter(|(u, _)| u == &url) {
                if complete(old, Some(&full)) != old {
                    fixes.push((url.clone(), old.clone(), full.clone()));
                }
            }
        }
    }
    println!(
        "Found {} recoverable cached titles across {} videos",
        fixes.len(),
        ids.len()
    );
    if apply {
        let tx = db.conn.transaction()?;
        let mut changed = 0;
        for (url, old, full) in fixes {
            // Compare the original title to avoid overwriting concurrent edits.
            changed += tx.execute(
                "UPDATE entries SET title=?1 WHERE url=?2 AND title=?3",
                rusqlite::params![full, url, old],
            )?;
        }
        tx.commit()?;
        println!("Restored {changed} playlist entries. Reopen the playlist to see updated names.");
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;
    #[test]
    fn restores_only_matching_complete_publisher_titles() {
        let title = "J.S. Bach: I. \"Wie schön leuchtet der...";
        let full = "J.S. Bach: I. \"Wie schön leuchtet der Morgenstern\"";
        let description = format!(
            "Provided to YouTube by Universal Music Group\n\n{full} · Orchestra\n\nAlbum\n\nAuto-generated by YouTube."
        );
        assert_eq!(
            from_snippet(&json!({"title":title,"description":description})),
            full
        );
        assert_eq!(complete(title, Some("Different work")), title);
        assert_eq!(
            complete("An intentional ending...", Some("An intentional ending")),
            "An intentional ending..."
        );
        assert_eq!(
            complete("Complete title", Some("Complete title with extra")),
            "Complete title"
        );
        assert_eq!(
            complete("Long…", Some("Longer complete title")),
            "Longer complete title"
        );
        assert_eq!(
            from_snippet(&json!({"title":title,"description":full})),
            title
        );
        assert_eq!(from_snippet(&json!({"title":title})), title);
    }
}
